#!/bin/sh
# Tests for ./softwary views (M2).
# shellcheck disable=SC2329,SC2119 # tests are called by run_tests; setup_repo takes optional flags
# shellcheck source=tests/lib.sh
. "$(dirname "$0")/lib.sh"

VIEW_REL=architecture/views/system.mmd

# AC-M2-04: every node and relationship appears in the view.
test_ac_m2_04_every_node_and_relationship() {
	setup_repo
	view=$REPO/$VIEW_REL
	[ -f "$view" ] || fail "view not generated"
	assert_match "$view" "^%% Generated by \./softwary views"
	assert_match "$view" "^flowchart LR$"
	assert_match "$view" '^  n1\(\["User"\]\)$'
	assert_match "$view" '^  n2\["API"\]$'
	assert_match "$view" '^  n3\[\("Accounts DB"\)\]$'
	assert_match "$view" '^  n1 -->\|"interacts"\| n2$'
	assert_match "$view" '^  n2 -->\|"JDBC"\| n3$'
}

# AC-M2-04: quotes in names do not break the diagram; containers are drawn.
test_ac_m2_04_escaping_and_containers() {
	setup_repo
	jq '.nodes[1].name = "The \"API\"" | .relationships += [{"unique-id": "c", "relationship-type": {"composed-of": {"container": "api", "nodes": ["db"]}}}, {"unique-id": "d", "relationship-type": {"deployed-in": {"container": "db", "nodes": ["api"]}}}]' \
		"$REPO/$MODEL_REL" >"$T/m" && mv "$T/m" "$REPO/$MODEL_REL"
	sw views
	assert_eq "$RC" 0 "exit code"
	view=$REPO/$VIEW_REL
	assert_match "$view" '^  n2\["The #quot;API#quot;"\]$'
	assert_match "$view" '^  n2 -\.->\|"composed-of"\| n3$'
	assert_match "$view" '^  n2 -\.->\|"deployed-in"\| n3$'
}

# AC-M2-04: the same model gives the same bytes.
test_ac_m2_04_deterministic() {
	setup_repo
	cp "$REPO/$VIEW_REL" "$T/first"
	sw views
	assert_eq "$RC" 0 "exit code"
	cmp -s "$T/first" "$REPO/$VIEW_REL" || fail "second run produced different bytes"
}

# AC-M2-04: --check writes nothing and reports missing or stale views.
test_ac_m2_04_check() {
	setup_repo
	sw views --check
	assert_eq "$RC" 0 "exit code when up to date"
	rm "$REPO/$VIEW_REL"
	sw views --check
	assert_eq "$RC" 1 "exit code when missing"
	assert_match "$OUT" "^missing +$VIEW_REL$"
	[ ! -e "$REPO/$VIEW_REL" ] || fail "--check wrote the view"
	sw views
	jq '.nodes[0].name = "Customer"' "$REPO/$MODEL_REL" >"$T/m" && mv "$T/m" "$REPO/$MODEL_REL"
	cp "$REPO/$VIEW_REL" "$T/before"
	sw views --check
	assert_eq "$RC" 1 "exit code when stale"
	assert_match "$OUT" "^stale +$VIEW_REL$"
	cmp -s "$T/before" "$REPO/$VIEW_REL" || fail "--check changed the view"
}

# AC-M2-04: an invalid model produces no view.
test_ac_m2_04_invalid_model() {
	setup_repo
	printf '{"nodes": []}\n' >"$REPO/$MODEL_REL"
	cp "$REPO/$VIEW_REL" "$T/before"
	sw views
	assert_eq "$RC" 1 "exit code"
	assert_contains "$OUT" "model validate"
	cmp -s "$T/before" "$REPO/$VIEW_REL" || fail "view changed for an invalid model"
	setup_repo_missing_model
}

setup_repo_missing_model() {
	rm "$REPO/$MODEL_REL"
	sw views
	assert_eq "$RC" 2 "exit code without a model"
}

run_tests "$0"
