#!/bin/sh
# Tests for ./softwary views (M2).
# shellcheck disable=SC2329,SC2119 # tests are called by run_tests; setup_repo takes optional flags
# shellcheck source=tests/lib.sh
. "$(dirname "$0")/lib.sh"

VIEW_REL=architecture/views/system.mmd

# AC-M2-04: every node and relationship appears in the view.
test_ac_m2_04_every_node_and_relationship() {
	setup_repo
	view=$REPO/$VIEW_REL
	[ -f "$view" ] || fail "view not generated"
	assert_match "$view" "^%% Generated by \./softwary views"
	assert_match "$view" "^flowchart LR$"
	assert_match "$view" '^  n1\(\["User"\]\)$'
	assert_match "$view" '^  n2\["API"\]$'
	assert_match "$view" '^  n3\[\("Accounts DB"\)\]$'
	assert_match "$view" '^  n1 -->\|"interacts"\| n2$'
	assert_match "$view" '^  n2 -->\|"JDBC"\| n3$'
}

# AC-M2-04: quotes in names do not break the diagram; containers are drawn.
test_ac_m2_04_escaping_and_containers() {
	setup_repo
	jq '.nodes[1].name = "The \"API\"" | .relationships += [{"unique-id": "c", "relationship-type": {"composed-of": {"container": "api", "nodes": ["db"]}}}, {"unique-id": "d", "relationship-type": {"deployed-in": {"container": "db", "nodes": ["api"]}}}]' \
		"$REPO/$MODEL_REL" >"$T/m" && mv "$T/m" "$REPO/$MODEL_REL"
	sw views
	assert_eq "$RC" 0 "exit code"
	view=$REPO/$VIEW_REL
	assert_match "$view" '^  n2\["The #quot;API#quot;"\]$'
	assert_match "$view" '^  n2 -\.->\|"composed-of"\| n3$'
	assert_match "$view" '^  n2 -\.->\|"deployed-in"\| n3$'
}

# AC-M2-04: the same model gives the same bytes.
test_ac_m2_04_deterministic() {
	setup_repo
	cp "$REPO/$VIEW_REL" "$T/first"
	sw views
	assert_eq "$RC" 0 "exit code"
	cmp -s "$T/first" "$REPO/$VIEW_REL" || fail "second run produced different bytes"
}

# AC-M2-04: --check writes nothing and reports missing or stale views.
test_ac_m2_04_check() {
	setup_repo
	sw views --check
	assert_eq "$RC" 0 "exit code when up to date"
	rm "$REPO/$VIEW_REL"
	sw views --check
	assert_eq "$RC" 1 "exit code when missing"
	assert_match "$OUT" "^missing +$VIEW_REL$"
	[ ! -e "$REPO/$VIEW_REL" ] || fail "--check wrote the view"
	sw views
	jq '.nodes[0].name = "Customer"' "$REPO/$MODEL_REL" >"$T/m" && mv "$T/m" "$REPO/$MODEL_REL"
	cp "$REPO/$VIEW_REL" "$T/before"
	sw views --check
	assert_eq "$RC" 1 "exit code when stale"
	assert_match "$OUT" "^stale +$VIEW_REL$"
	cmp -s "$T/before" "$REPO/$VIEW_REL" || fail "--check changed the view"
}

# AC-M2-04: an invalid model produces no view.
test_ac_m2_04_invalid_model() {
	setup_repo
	printf '{"nodes": []}\n' >"$REPO/$MODEL_REL"
	cp "$REPO/$VIEW_REL" "$T/before"
	sw views
	assert_eq "$RC" 1 "exit code"
	assert_contains "$OUT" "model validate"
	cmp -s "$T/before" "$REPO/$VIEW_REL" || fail "view changed for an invalid model"
	setup_repo_missing_model
}

setup_repo_missing_model() {
	rm "$REPO/$MODEL_REL"
	sw views
	assert_eq "$RC" 2 "exit code without a model"
}

STATES_VIEW=architecture/views/states-order.mmd
FLOW_VIEW=architecture/views/flow-signin.mmd

# formal_ready: a repo with a blueprint, the order's state machine and its views.
formal_ready() {
	setup_repo
	add_product
	add_blueprint
	add_formal
}

# AC-V5-09: a state diagram for every state machine, a sequence diagram for
# every flow, both from their files.
test_ac_v5_09_state_and_flow_views() {
	formal_ready
	sw views
	assert_eq "$RC" 0 "exit code"
	v=$REPO/$STATES_VIEW
	assert_match "$v" "^%% generated by \\./softwary views from architecture/states/order\\.json$"
	assert_match "$v" "^stateDiagram-v2$"
	assert_match "$v" "^  \\[\\*\\] --> created$"
	assert_match "$v" "^  created --> paid : pay$"
	assert_match "$v" "^  created --> cancelled : cancel$"
	assert_match "$v" "^  paid --> shipped : ship$"
	assert_match "$v" "^  shipped --> \\[\\*\\]$"
	assert_match "$v" "^  cancelled --> \\[\\*\\]$"
	assert_no_match "$v" "^  paid --> \\[\\*\\]$"
	f=$REPO/$FLOW_VIEW
	assert_match "$f" "^%% generated by \\./softwary views from architecture/flows/signin\\.json$"
	assert_match "$f" "^sequenceDiagram$"
	assert_match "$f" "^  participant api as API$"
	assert_match "$f" "^  user->>api: Send the email and the password \\(credentials\\)$"
	assert_match "$f" "^  db->>api: Return the member$"
	cp "$f" "$T/first"
	sw views
	assert_match "$OUT" "views: up to date"
	cmp -s "$T/first" "$f" || fail "second run produced different bytes"
}

# AC-V5-09: a generated view whose source is gone is deleted; a hand-written
# one, and the other files of the directory, stay.
test_ac_v5_09_orphan_removed_handwritten_kept() {
	formal_ready
	sw views
	printf 'stateDiagram-v2\n  [*] --> a\n' >"$REPO/architecture/views/states-hand.mmd"
	printf 'notes\n' >"$REPO/architecture/views/README.md"
	rm "$REPO/architecture/states/order.json" "$REPO/architecture/flows/signin.json"
	sw views
	assert_eq "$RC" 0 "exit code"
	assert_match "$OUT" "^views: removed $STATES_VIEW$"
	assert_match "$OUT" "^views: removed $FLOW_VIEW$"
	[ ! -e "$REPO/$STATES_VIEW" ] || fail "orphan state view kept"
	[ ! -e "$REPO/$FLOW_VIEW" ] || fail "orphan flow view kept"
	[ -f "$REPO/architecture/views/states-hand.mmd" ] || fail "hand-written view removed"
	[ -f "$REPO/architecture/views/README.md" ] || fail "README removed"
	[ -f "$REPO/$VIEW_REL" ] || fail "system view removed"
}

# AC-V5-09: --check reports a missing, a stale and an orphan view, writes and
# deletes nothing.
test_ac_v5_09_check() {
	formal_ready
	rm "$REPO/$STATES_VIEW" "$REPO/$FLOW_VIEW"
	sw views --check
	assert_eq "$RC" 1 "exit code with the new views missing"
	assert_match "$OUT" "^missing +$STATES_VIEW$"
	assert_match "$OUT" "^missing +$FLOW_VIEW$"
	[ ! -e "$REPO/$STATES_VIEW" ] || fail "--check wrote a view"
	sw views
	sw views --check
	assert_eq "$RC" 0 "exit code when up to date"
	jq '.transitions[0].event = "settle"' "$REPO/architecture/states/order.json" >"$T/s" && mv "$T/s" "$REPO/architecture/states/order.json"
	sw views --check
	assert_eq "$RC" 1 "exit code when stale"
	assert_match "$OUT" "^stale +$STATES_VIEW$"
	cp "$REPO/$FLOW_VIEW" "$T/before"
	rm "$REPO/architecture/flows/signin.json"
	sw views --check
	assert_match "$OUT" "^orphan +$FLOW_VIEW$"
	[ -f "$REPO/$FLOW_VIEW" ] || fail "--check deleted the orphan"
	cmp -s "$T/before" "$REPO/$FLOW_VIEW" || fail "--check changed a view"
}

# AC-V5-09: an invalid flow or state machine produces no diagram.
test_ac_v5_09_invalid_source() {
	formal_ready
	sw views
	cp "$REPO/$STATES_VIEW" "$T/before"
	jq '.initial = "nowhere"' "$REPO/architecture/states/order.json" >"$T/s" && mv "$T/s" "$REPO/architecture/states/order.json"
	sw views
	assert_eq "$RC" 1 "exit code"
	assert_contains "$OUT" "blueprint check"
	cmp -s "$T/before" "$REPO/$STATES_VIEW" || fail "the view changed for an invalid state machine"
}

run_tests "$0"
