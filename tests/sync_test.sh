# AC-M1-08: verify runs the sync check first; drift fails it and the other checks still run.
test_ac_m1_08_verify_runs_sync_first() {
	setup_repo
	conf_all true
	sw verify
	assert_eq "$RC" 0 "exit code when synced"
	first=$(grep -E '^[a-z_-]+ +(PASS|FAIL|SKIP)' "$OUT" | head -n 1)
	case $first in sync\ *PASS*) ;; *) fail "first check is not a passing sync: [$first]" ;; esac
	awk '{ print } /^<!-- softwary:begin/ { print "hand edit" }' "$REPO/AGENTS.md" >"$T/agents"
	cp "$T/agents" "$REPO/AGENTS.md"
	sw verify
	assert_eq "$RC" 1 "exit code with drift"
	assert_match "$OUT" "^sync +FAIL "
	assert_match "$OUT" "AGENTS\.md"
	assert_match "$OUT" "^lint +PASS "
}

# AC-M1-10: a new tool is one script in targets/ plus one line in tools.conf.
test_ac_m1_10_new_target_is_one_script() {
	setup_repo
	snapshot >"$T/before"
	cat >"$REPO/.softwary/targets/foo.sh" <<'EOF'
#!/bin/sh
# Sample target used by the tests: copies the rules to .foo/rules.md.
set -eu
mkdir -p "$2/.foo"
cp "$1/rules/core.md" "$2/.foo/rules.md"
EOF
	printf 'foo = on\n' >>"$REPO/.softwary/config/tools.conf"
	sw sync
	assert_eq "$RC" 0 "exit code"
	[ -f "$REPO/.foo/rules.md" ] || fail "new target produced nothing"
	snapshot >"$T/after"
	assert_eq "$(changed_paths "$T/before" "$T/after" | tr '\n' ' ')" \
		".foo/rules.md .softwary/config/tools.conf .softwary/generated .softwary/targets/foo.sh " "changed files"
}

