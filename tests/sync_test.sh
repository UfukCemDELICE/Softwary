# AC-M1-06: a same-named source under .softwary/local/ replaces the managed one.
test_ac_m1_06_local_overrides_managed() {
	setup_repo --no-sync
	add_sources
	l=$REPO/.softwary/local
	mkdir -p "$l/rules" "$l/skills/hello" "$l/agents"
	printf '# Local rules\n\nLocal rule only.\n' >"$l/rules/core.md"
	printf -- '---\nname: hello\ndescription: Local hello.\n---\nLocal skill body.\n' >"$l/skills/hello/SKILL.md"
	printf -- '---\nname: helper\ndescription: Local helper.\n---\nLocal agent body.\n' >"$l/agents/helper.md"
	tools_all on
	sw sync
	assert_eq "$RC" 0 "exit code"
	assert_contains "$REPO/AGENTS.md" "Local rule only."
	assert_no_match "$REPO/AGENTS.md" "Never weaken"
	assert_contains "$REPO/.cursor/skills/softwary-hello/SKILL.md" "description: Local hello."
	[ ! -e "$REPO/.cursor/skills/softwary-hello/references" ] || fail "managed skill files leaked into the local skill"
	assert_contains "$REPO/.claude/agents/helper.md" "Local agent body."
	assert_contains "$REPO/.codex/agents/helper.toml" "Local agent body."
}

