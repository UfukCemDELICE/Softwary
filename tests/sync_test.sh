# AC-M1-05: each agent goes to every tool; the Codex file is valid TOML with the three fields.
test_ac_m1_05_agents_written_per_tool() {
	command -v python3 >/dev/null || fail "python3 is required to validate TOML"
	setup_repo --no-sync
	add_sources
	tools_all on
	sw sync
	assert_eq "$RC" 0 "exit code"
	for d in .claude/agents .cursor/agents; do
		f=$REPO/$d/helper.md
		[ -f "$f" ] || fail "missing $d/helper.md"
		assert_eq "$(frontmatter "$f")" 'name: helper
description: "A sample agent: quotes \"and\" colons."' "frontmatter in $d"
		assert_contains "$f" "You are a helper."
	done
	toml=$REPO/.codex/agents/helper.toml
	[ -f "$toml" ] || fail "missing .codex/agents/helper.toml"
	python3 - "$toml" >"$OUT" 2>&1 <<'EOF' || fail "invalid Codex agent TOML"
import sys, tomllib
with open(sys.argv[1], "rb") as f:
    d = tomllib.load(f)
assert set(d) == {"name", "description", "developer_instructions"}, d
assert d["name"] == "helper", d["name"]
assert d["description"] == 'A sample agent: quotes "and" colons.', d["description"]
body = d["developer_instructions"]
assert body.startswith("You are a helper."), body
assert 'Keep "quotes", back\\slashes and """triple quotes""" intact.' in body, body
EOF
}

# AC-M1-05: an agent with an empty body or without a name is refused.
