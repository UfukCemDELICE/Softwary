# AC-M1-08: --check names every kind of drift, exits 1 and writes nothing.
test_ac_m1_08_check_reports_and_writes_nothing() {
	setup_repo --no-sync
	add_sources
	mkdir -p "$REPO/.softwary/local/skills/extra"
	printf -- '---\nname: extra\ndescription: Extra.\n---\nExtra.\n' >"$REPO/.softwary/local/skills/extra/SKILL.md"
	tools_all on
	sw sync
	assert_eq "$RC" 0 "first sync"
	rm "$REPO/.cursor/agents/helper.md"
	printf 'edited\n' >>"$REPO/.claude/agents/helper.md"
	sed 's/^description: .*/description: Changed./' "$REPO/.softwary/skills/hello/SKILL.md" >"$T/skill"
	cp "$T/skill" "$REPO/.softwary/skills/hello/SKILL.md"
	rm -r "$REPO/.softwary/local/skills/extra"
	snapshot >"$T/before"
	sw sync --check
	snapshot >"$T/after"
	assert_eq "$RC" 1 "exit code"
	cmp -s "$T/before" "$T/after" || fail "--check wrote: $(changed_paths "$T/before" "$T/after")"
	assert_match "$OUT" "^missing +\.cursor/agents/helper\.md$"
	assert_match "$OUT" "^modified +\.claude/agents/helper\.md \(edited by hand\)$"
	assert_match "$OUT" "^stale +\.agents/skills/softwary-hello/SKILL\.md$"
	assert_match "$OUT" "^orphan +\.claude/skills/softwary-extra/SKILL\.md$"
}

