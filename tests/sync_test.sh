# AC-M1-07: files that belong to the project are never touched.
test_ac_m1_07_project_files_untouched() {
	setup_repo --no-sync
	add_sources
	mkdir -p "$REPO/.claude/agents" "$REPO/.claude/skills/mine" "$REPO/.cursor/rules"
