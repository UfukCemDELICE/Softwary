# AC-M1-04: each skill goes to every enabled tool as softwary-<name> with only name and description.
test_ac_m1_04_skills_written_per_tool() {
	setup_repo --no-sync
	add_sources
	tools_all on
	sw sync
	assert_eq "$RC" 0 "exit code"
	for d in .claude/skills .cursor/skills .agents/skills; do
		f=$REPO/$d/softwary-hello/SKILL.md
		[ -f "$f" ] || fail "missing $d/softwary-hello/SKILL.md"
		assert_eq "$(sed -n 1p "$f")" "---" "first line of $d"
		assert_eq "$(frontmatter "$f")" "name: softwary-hello
description: Greets the user. Use when a test needs a sample skill." "frontmatter in $d"
		assert_contains "$f" "Say hello."
		assert_contains "$f" "Do not edit"
		[ -f "$REPO/$d/softwary-hello/references/notes.md" ] || fail "reference file not copied to $d"
	done
}

# expect_source_rejected TEXT: sync exits 2 naming TEXT and writes no tool output.
expect_source_rejected() {
	tools_all on
	sw sync
	assert_eq "$RC" 2 "exit code"
	assert_contains "$OUT" "$1"
	[ ! -e "$REPO/.claude" ] && [ ! -e "$REPO/.cursor" ] && [ ! -e "$REPO/.agents" ] || fail "output written despite the error"
}

