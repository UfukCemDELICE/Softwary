#!/bin/sh
# Tests for ./softwary sync (M1).
# shellcheck disable=SC2329,SC2119 # tests are called by run_tests; setup_repo takes optional flags
# shellcheck source=tests/lib.sh
. "$(dirname "$0")/lib.sh"

# frontmatter FILE: the lines between the opening and closing '---'.
frontmatter() {
	awk 'NR == 1 { next } /^---$/ { exit } { print }' "$1"
}

# AC-M1-01: the first sync creates the managed blocks in AGENTS.md and CLAUDE.md.
test_ac_m1_01_first_sync_creates_blocks() {
	setup_repo --no-sync
	tools_all on
	sw sync
	assert_eq "$RC" 0 "exit code"
	assert_match "$REPO/AGENTS.md" "^<!-- softwary:begin"
	assert_match "$REPO/AGENTS.md" "^<!-- softwary:end -->$"
	assert_contains "$REPO/AGENTS.md" "./softwary verify"
	assert_match "$REPO/CLAUDE.md" "^@AGENTS\.md$"
	[ -f "$REPO/.softwary/generated" ] || fail "manifest missing"
}

# AC-M1-02: own content before the block is kept byte for byte; the block is appended.
test_ac_m1_02_appends_block_when_absent() {
	setup_repo --no-sync
	printf '# My project\n\nOwn rules.\n' >"$REPO/AGENTS.md"
	printf '# Claude notes' >"$REPO/CLAUDE.md" # no trailing newline
	cp "$REPO/AGENTS.md" "$T/agents.orig"
	cp "$REPO/CLAUDE.md" "$T/claude.orig"
	tools_all on
	sw sync
	assert_eq "$RC" 0 "exit code"
	head -c "$(wc -c <"$T/agents.orig")" "$REPO/AGENTS.md" | cmp -s - "$T/agents.orig" || fail "AGENTS.md prefix changed"
	head -c "$(wc -c <"$T/claude.orig")" "$REPO/CLAUDE.md" | cmp -s - "$T/claude.orig" || fail "CLAUDE.md prefix changed"
	own=$(grep -n '^Own rules\.$' "$REPO/AGENTS.md" | cut -d: -f1)
	begin=$(grep -n '^<!-- softwary:begin' "$REPO/AGENTS.md" | cut -d: -f1)
	[ "$own" -lt "$begin" ] || fail "block not appended after own content"
}

# AC-M1-02: an existing block is updated in place; text around it is unchanged.
test_ac_m1_02_updates_block_in_place() {
	setup_repo --no-sync
	printf '# My project\n\nOwn rules.\n' >"$REPO/AGENTS.md"
	tools_all on
	sw sync
	printf '\nTrailing own text.\n' >>"$REPO/AGENTS.md"
	outside_block "$REPO/AGENTS.md" >"$T/outside.before"
	mkdir -p "$REPO/.softwary/local/rules"
	{ cat "$REPO/.softwary/rules/core.md"; printf 'Extra rule.\n'; } >"$REPO/.softwary/local/rules/core.md"
	sw sync
	assert_eq "$RC" 0 "exit code"
	outside_block "$REPO/AGENTS.md" >"$T/outside.after"
	cmp -s "$T/outside.before" "$T/outside.after" || fail "content outside the block changed"
	block_of "$REPO/AGENTS.md" >"$T/block"
	assert_contains "$T/block" "Extra rule."
	assert_eq "$(grep -c '^<!-- softwary:begin' "$REPO/AGENTS.md")" 1 "number of blocks"
	assert_eq "$(tail -n 1 "$REPO/AGENTS.md")" "Trailing own text." "last line"
}

# AC-M1-02: a second sync changes nothing.
test_ac_m1_02_second_sync_changes_nothing() {
