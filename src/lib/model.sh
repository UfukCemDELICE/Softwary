# shellcheck shell=sh
# shellcheck disable=SC2034 # SW_* globals are read by verify.sh, doctor.sh and the other libs
# softwary: `model validate` and `views`. Sourced by bin/softwary. POSIX sh.
#
# The model is architecture/model/system.calm.json (CALM 1.3). lib/model.jq
# holds the checks and lib/views.jq the Mermaid view.

SW_MODEL_REL=architecture/model/system.calm.json
SW_VIEW_REL=architecture/views/system.mmd
SW_MODEL_MISSING="$SW_MODEL_REL not found; start from .softwary/templates/system.calm.json"

# sw_model_check: prints one "<file>: <path>: <problem>" line per problem.
# Returns 0 valid, 1 problems, 2 no model file.
sw_model_check() {
	_mf=$SOFTWARY_ROOT/$SW_MODEL_REL
	[ -f "$_mf" ] || return 2
	if ! _merr=$(jq empty "$_mf" 2>&1); then
		printf '%s: invalid JSON: %s\n' "$SW_MODEL_REL" "$(printf '%s\n' "$_merr" | head -n 1)"
		return 1
	fi
	_mout=$(jq -r -f "$SOFTWARY_HOME/lib/model.jq" "$_mf") || {
		printf '%s: could not be checked (jq failed)\n' "$SW_MODEL_REL"
		return 1
	}
	[ -n "$_mout" ] || return 0
	printf '%s\n' "$_mout" | sed "s|^|$SW_MODEL_REL: |"
	return 1
}

sw_model() {
	if [ $# -ne 1 ] || [ "$1" != validate ]; then
		printf 'usage: ./softwary model validate\n' >&2
		return 2
	fi
	_rc=0
	_probs=$(sw_model_check) || _rc=$?
	case $_rc in
	0)
		printf 'model: valid (%s)\n' "$(jq -r '"\(.nodes | length) nodes, \(.relationships // [] | length) relationships"' \
			"$SOFTWARY_ROOT/$SW_MODEL_REL")"
		return 0
		;;
	2)
		printf 'model: %s\n' "$SW_MODEL_MISSING"
		return 2
		;;
	esac
	printf '%s\n' "$_probs"
	printf 'model: %s problem(s)\n' "$(printf '%s\n' "$_probs" | wc -l | tr -d ' ')"
	return 1
}

# sw_views_render DIR: renders every view of the blueprint into DIR (one file
# named like the view's file under architecture/views/) and prints the names,
# one per line: system.mmd, states-<entity>.mmd for each state machine and
# flow-<id>.mmd for each flow. Returns 1 when jq fails.
sw_views_render() {
	jq -r -f "$SOFTWARY_HOME/lib/views.jq" "$SOFTWARY_ROOT/$SW_MODEL_REL" >"$1/system.mmd" || return 1
	printf 'system.mmd\n'
	for _vr in $(sw_json_files "$SW_STATES_DIR"); do
		_vn=${_vr##*/}
		jq -r --arg src "$_vr" -f "$SOFTWARY_HOME/lib/states-view.jq" "$SOFTWARY_ROOT/$_vr" >"$1/states-${_vn%.json}.mmd" || return 1
		printf 'states-%s.mmd\n' "${_vn%.json}"
	done
	_vnames=$(jq -c '[.nodes[]? | objects | select(."unique-id" | type == "string") | {key: ."unique-id", value: (.name // ."unique-id")}] | from_entries' \
		"$SOFTWARY_ROOT/$SW_MODEL_REL") || return 1
	for _vr in $(sw_json_files "$SW_FLOWS_DIR"); do
		_vn=${_vr##*/}
		jq -r --arg src "$_vr" --argjson names "$_vnames" -f "$SOFTWARY_HOME/lib/flow-view.jq" "$SOFTWARY_ROOT/$_vr" >"$1/flow-${_vn%.json}.mmd" || return 1
		printf 'flow-%s.mmd\n' "${_vn%.json}"
	done
}

# sw_views_orphans WANTED: the generated state and flow views under
# architecture/views/ (found by their first line) that are not in WANTED (the
# names sw_views_render printed), one repo-relative path per line. A file
# without that line is hand-written and is never listed.
sw_views_orphans() {
	for _vo in "$SOFTWARY_ROOT"/architecture/views/states-*.mmd "$SOFTWARY_ROOT"/architecture/views/flow-*.mmd; do
		[ -f "$_vo" ] || continue
		case $(head -n 1 "$_vo") in "%% generated by ./softwary views from "*) ;; *) continue ;; esac
		printf '%s\n' "$1" | grep -Fqx -e "${_vo##*/}" || printf 'architecture/views/%s\n' "${_vo##*/}"
	done
}

# sw_views [--check]: writes the views of the blueprint (the system diagram
# from the model, a state diagram for each state machine, a sequence diagram
# for each flow) under architecture/views/ and deletes the generated ones whose
# source is gone; with --check reports a missing, stale or orphan view without
# touching anything.
sw_views() {
	_check=0
	for _a in "$@"; do
		case $_a in
		--check) _check=1 ;;
		*)
			printf 'usage: ./softwary views [--check]\n' >&2
			return 2
			;;
		esac
	done
	_rc=0
	sw_model_check >/dev/null || _rc=$?
	case $_rc in
	2)
		printf 'views: %s\n' "$SW_MODEL_MISSING"
		return 2
		;;
	1)
		printf 'views: the model is invalid; run ./softwary model validate\n'
		return 1
		;;
	esac
	_vbad=$({ sw_flows_check; sw_states_check; } | grep -E '^architecture/(flows|states)/[^:]+\.json: ' || :)
	if [ -n "$_vbad" ]; then
		printf 'views: a flow or a state machine is invalid; run ./softwary blueprint check\n'
		return 1
	fi
	_vtmp=$(mktemp -d "${TMPDIR:-/tmp}/softwary-view.XXXXXX") || return 2
	if ! _vwant=$(sw_views_render "$_vtmp"); then
		rm -rf "$_vtmp"
		printf 'views: could not render the blueprint (jq failed)\n'
		return 1
	fi
	_vorph=$(sw_views_orphans "$_vwant")
	_vrc=0
	for _vf in $_vwant; do
		_vrel=architecture/views/$_vf
		_view=$SOFTWARY_ROOT/$_vrel
		if [ "$_check" -eq 1 ]; then
			if [ ! -f "$_view" ]; then
				printf '%-8s %s\n' missing "$_vrel"
				_vrc=1
			elif ! cmp -s "$_vtmp/$_vf" "$_view"; then
				printf '%-8s %s\n' stale "$_vrel"
				_vrc=1
			fi
		elif [ ! -f "$_view" ] || ! cmp -s "$_vtmp/$_vf" "$_view"; then
			{ mkdir -p "$(dirname "$_view")" && cp "$_vtmp/$_vf" "$_view"; } || { rm -rf "$_vtmp"; return 2; }
			printf 'views: wrote %s\n' "$_vrel"
			_vrc=1
		fi
	done
	for _vo in $_vorph; do
		if [ "$_check" -eq 1 ]; then
			printf '%-8s %s\n' orphan "$_vo"
		else
			rm -f "$SOFTWARY_ROOT/$_vo"
			printf 'views: removed %s\n' "$_vo"
		fi
		_vrc=1
	done
	rm -rf "$_vtmp"
	if [ "$_check" -eq 1 ]; then
		if [ "$_vrc" -eq 0 ]; then
			printf 'views --check: up to date\n'
		else
			printf 'views --check: out of date; run ./softwary views\n'
		fi
		return "$_vrc"
	fi
	[ "$_vrc" -ne 0 ] || printf 'views: up to date\n'
	return 0
}
