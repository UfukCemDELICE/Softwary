# shellcheck shell=sh
# softwary: helpers for target scripts. A target is called as
#
#   sh <target>.sh SRC FILES BLOCKS
#
# SRC holds the validated sources: rules/core.md, skills/softwary-<name>/,
# agents/<name>.md (frontmatter: name and description only). The target
# writes whole files under FILES and block contents under BLOCKS, both by
# repo-relative path. It writes nothing else.

# sw_copy_skills SRC DEST: copies every skill directory into DEST.
sw_copy_skills() {
	for _d in "$1"/skills/*/; do
		[ -d "$_d" ] || continue
		mkdir -p "$2"
		cp -R "${_d%/}" "$2/"
	done
}

# sw_copy_agents SRC DEST: copies every agent file (Markdown) into DEST.
sw_copy_agents() {
	for _f in "$1"/agents/*.md; do
		[ -f "$_f" ] || continue
		mkdir -p "$2"
		cp "$_f" "$2/"
	done
}

# sw_agent_model SRC TOOL NAME: the model id models.conf gives agent NAME in
# TOOL; nothing when it gives none (no models.conf, or one that is not usable).
sw_agent_model() {
	[ -f "$1/models/$2/$3" ] || return 0
	cat "$1/models/$2/$3"
}

# sw_copy_agents_tool SRC DEST TOOL: like sw_copy_agents, with the `model:`
# line of the frontmatter replaced by the model id of TOOL (sw_agent_model), or
# dropped when there is none.
sw_copy_agents_tool() {
	for _f in "$1"/agents/*.md; do
		[ -f "$_f" ] || continue
		mkdir -p "$2"
		_m=$(sw_agent_model "$1" "$3" "$(basename "$_f" .md)")
		awk -v m="$_m" '
			NR == 1 { print; next }
			!closed && $0 == "---" { if (m != "") print "model: " m; closed = 1; print; next }
			!closed && index($0, "model: ") == 1 { next }
			{ print }' "$_f" >"$2/${_f##*/}"
	done
}

# sw_fm_value FILE KEY: the value of a frontmatter field, YAML quotes removed.
sw_fm_value() {
	_v=$(awk -v k="$2" 'NR == 1 { next } /^---$/ { exit } index($0, k ": ") == 1 { print substr($0, length(k) + 3); exit }' "$1")
	case $_v in
	\"*\")
		_v=${_v#\"}
		_v=${_v%\"}
		printf '%s' "$_v" | sed 's/\\"/"/g; s/\\\\/\\/g'
		;;
	\'*\')
		_v=${_v#\'}
		_v=${_v%\'}
		printf '%s' "$_v" | sed "s/''/'/g"
		;;
	*) printf '%s' "$_v" ;;
	esac
}

# sw_doc_body FILE: the body after the frontmatter, without the generated
# note and leading blank lines.
sw_doc_body() {
	awk 'NR == 1 { next }
		!fm_done { if ($0 == "---") fm_done = 1; next }
		!started && /^<!-- Generated by \.\/softwary sync/ { next }
		!started && /^[[:space:]]*$/ { next }
		{ started = 1; print }' "$1"
}

# sw_toml_escape: escapes stdin for a TOML basic string.
sw_toml_escape() {
	sed 's/\\/\\\\/g; s/"/\\"/g'
}

# sw_agent_toml FILE [MODEL]: a Codex custom agent (TOML) from an agent file,
# with `model = "<MODEL>"` when MODEL is given.
sw_agent_toml() {
	printf '# Generated by ./softwary sync. Do not edit.\n'
	printf 'name = "%s"\n' "$(sw_fm_value "$1" name | sw_toml_escape)"
	printf 'description = "%s"\n' "$(sw_fm_value "$1" description | sw_toml_escape)"
	[ -z "${2-}" ] || printf 'model = "%s"\n' "$(printf '%s' "$2" | sw_toml_escape)"
	printf 'developer_instructions = """\n'
	sw_doc_body "$1" | sw_toml_escape
	printf '"""\n'
}
